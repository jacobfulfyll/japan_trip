// data/days.js — single source of truth for the trip. Edit days here; the
// site renders from this. No build step. (ES module: app.js imports it.)
//
// Schema (full definition in .pipeline/data-model-and-scaffold/task.md):
//   TRIP: { title, start, end, travelers[], eveningWindow:{startHour,endHour} }
//   DAYS[]: {
//     date,                       // ISO "YYYY-MM-DD"; Day N derived from TRIP.start
//     base, title, intro,
//     spend?,                     // optional string
//     photos: [{ url, alt, credit? }], // hype slideshow; [] = none yet (credit required for CC-licensed images)
//     lodging: { name, address, mapUrl, coords?, breakfast? } | null,
//     prep: [".."],               // free-text; powers the evening "Prep for tomorrow"
//     plan: [{ time?, tag, title, note?, mapUrl?, coords?, reserved?,
//              transit?,           // TransitLeg & { minutes?: number, transfer?: TransitLeg } — see below
//              recommendations?: [{ name, pros: [".."], con, mapUrl?, coords?, address?,
//                                   transit?  // TransitLeg & { minutes: number, transfer?: TransitLeg } — see below
//                                 }] }],
//   RULE: a plan item carries AT MOST 4 recommendations.
//   }
//
// Tag strings (plan[].tag): 'meal' | 'transit' | 'sight' | 'checkin' |
//   'checkout' | 'reservation' | 'rest' | 'bar' | 'spa'.
//
// Shared sub-shape — TransitLeg (used by plan[].transit AND recommendations[].transit).
// Declared here so both surfaces stay aligned.
//   TransitLeg: {
//     mode: 'bus' | 'train' | 'subway',  // drives the mode-aware tag pill + emoji
//     line?: string,                      // e.g. "Hakone Tozan Bus", "Tokaido Shinkansen (Hikari)"
//     from: string,                       // boarding stop
//     to: string,                         // alighting stop
//   }
// On plan items, `transit` extends TransitLeg with two optionals:
//   minutes?: number                       // single source of truth for duration (strip from `note` prose)
//   transfer?: TransitLeg                  // one mid-trip transfer (3+ legs out of scope)
// On recommendations, `transit` is authored ONLY when the rec's walk-from-anchor
// exceeds 1.5km (the inline transit-alternative pill). Shape matches plan-item
// transit, but `minutes` is REQUIRED (door-to-door total, including walk to/from
// stops) since the render shows a single duration. 3+ leg journeys are out of
// scope — drop such recs rather than extending the schema.
// NOTE: being authored incrementally during grooming. Kyoto first. Days other
// than those groomed are not yet present; the build task fills the full 18.

